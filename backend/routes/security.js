const router = require('express').Router();
const pool = require('../db');
const auth = require('../middleware/auth');

router.get('/', auth, async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM security_alerts ORDER BY created_at DESC');
    res.json(result.rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.get('/:id', auth, async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM security_alerts WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.post('/', auth, async (req, res) => {
  try {
    const { type, severity, message, location, device_id, icon } = req.body;
    const result = await pool.query(
      'INSERT INTO security_alerts (type, severity, message, location, device_id, icon) VALUES ($1,$2,$3,$4,$5,$6) RETURNING *',
      [type, severity, message, location, device_id, icon || '⚠️']
    );
    res.status(201).json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.put('/:id', auth, async (req, res) => {
  try {
    const { type, severity, message, location, device_id, is_resolved, icon } = req.body;
    const result = await pool.query(
      'UPDATE security_alerts SET type=$1, severity=$2, message=$3, location=$4, device_id=$5, is_resolved=$6, icon=$7, resolved_at=$8 WHERE id=$9 RETURNING *',
      [type, severity, message, location, device_id, is_resolved, icon, is_resolved ? new Date() : null, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.delete('/:id', auth, async (req, res) => {
  try {
    const result = await pool.query('DELETE FROM security_alerts WHERE id = $1 RETURNING *', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json({ message: 'Deleted successfully' });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

module.exports = router;
